export type UiStringKey = keyof typeof uiStrings;

export function aboard(members: number): string {
  return `${members} a bordo`;
}

export function homeTomorrowAt(hhmm: string): string {
  return `Amanhã ${hhmm}`;
}

export function favoriteLine(short: string): string {
  return `Favoritar linha ${short}`;
}

export function unfavoriteLine(short: string): string {
  return `Remover linha ${short} dos favoritos`;
}

export function typicalDelayOf(minutes: number): string {
  return `Costuma atrasar cerca de ${minutes} min neste horário`;
}

export function confidenceLabel(level: number): string {
  if (level <= 0) return uiStrings.confLow;
  if (level === 1) return uiStrings.confMid;
  return uiStrings.confHigh;
}

export function agoShort(secondsS: number): string {
  const s = secondsS < 0 ? 0 : secondsS;
  if (s < 60) return `há ${s} s`;
  const minutes = Math.floor(s / 60);
  if (minutes < 60) return `há ${minutes} min`;
  return `há ${Math.floor(minutes / 60)} h`;
}

export function lastSentAgo(ago: string): string {
  return `Última posição enviada ${ago}`;
}
